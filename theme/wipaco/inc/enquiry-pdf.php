<?php
/**
 * Quote request PDFs: attached to the notification email and downloadable from
 * Enquiries in the admin. PDFs are generated on demand from the saved enquiry,
 * so no customer files are left lying on the server.
 */

require_once get_template_directory() . '/vendor/autoload.php';

use Dompdf\Dompdf;
use Dompdf\Options;

/** Reference number shown to the customer, e.g. Q261022-67. */
function wipaco_enquiry_ref( $post_id ) {
	return 'Q' . get_post_time( 'ymd', false, $post_id ) . '-' . $post_id;
}

/** Saved form fields (label => value) for an enquiry. */
function wipaco_enquiry_data( $post_id ) {
	$data = get_post_meta( $post_id, '_wipaco_enquiry', true );
	return is_array( $data ) ? $data : array();
}

/** Builds the PDF for an enquiry and returns it as a binary string. */
function wipaco_enquiry_pdf( $post_id ) {
	$theme = get_template_directory();
	$data  = wipaco_enquiry_data( $post_id );
	$rows  = '';
	foreach ( $data as $label => $value ) {
		if ( $value !== '' ) {
			$rows .= '<tr><th>' . esc_html( $label ) . '</th><td>' . nl2br( esc_html( $value ) ) . '</td></tr>';
		}
	}
	$phones = implode( ' / ', array_filter( array( wipaco_contact( 'phone_1' ), wipaco_contact( 'phone_2' ) ) ) );

	$html = '<!doctype html><html><head><meta charset="utf-8"><style>
		@page { margin: 18mm 16mm; }
		body { font-family: "DejaVu Sans", sans-serif; font-size: 10.5pt; color: #17202f; }
		.head { border-bottom: 2px solid #2160d2; padding-bottom: 10px; margin-bottom: 18px; }
		.head img { width: 170px; }
		.head .co { float: right; text-align: right; font-size: 8.5pt; color: #5a6577; line-height: 1.5; }
		h1 { font-size: 17pt; color: #0c1b38; margin: 0 0 4px; }
		.meta { color: #5a6577; margin-bottom: 18px; }
		.meta b { color: #2e7d32; }
		table { width: 100%; border-collapse: collapse; }
		th, td { text-align: left; vertical-align: top; padding: 9px 10px; border-bottom: 1px solid #e2e8f0; }
		th { width: 28%; background: #f3f6fb; color: #5a6577; font-weight: normal; }
		.foot { position: fixed; bottom: -8mm; left: 0; right: 0; font-size: 8pt; color: #8a94a6; text-align: center; }
	</style></head><body>
		<div class="foot">Generated by the Wipaco website quote form</div>
		<div class="head">
			<div class="co">' . esc_html( wipaco_contact( 'address' ) ) . '<br>Tel: ' . esc_html( $phones ) . ' &middot; WhatsApp: ' . esc_html( wipaco_whatsapp_display() ) . '<br>' . esc_html( wipaco_contact( 'email' ) ) . '</div>
			<img src="' . esc_attr( $theme . '/assets/img/logo.png' ) . '">
		</div>
		<h1>Quote Request</h1>
		<div class="meta">Reference <b>' . esc_html( wipaco_enquiry_ref( $post_id ) ) . '</b> &middot; Received ' . esc_html( get_post_time( 'j F Y, H:i', false, $post_id ) ) . '</div>
		<table>' . $rows . '</table>
	</body></html>';

	$options = new Options();
	$options->set( 'chroot', $theme );
	$options->set( 'isRemoteEnabled', false );
	$options->set( 'defaultFont', 'DejaVu Sans' );
	$dompdf = new Dompdf( $options );
	$dompdf->loadHtml( $html, 'UTF-8' );
	$dompdf->setPaper( 'A4' );
	$dompdf->render();
	return $dompdf->output();
}

function wipaco_enquiry_pdf_filename( $post_id ) {
	return 'Quote-Request-' . wipaco_enquiry_ref( $post_id ) . '.pdf';
}

/* ---------- Admin: download PDF, reply on WhatsApp ---------- */

function wipaco_enquiry_pdf_url( $post_id ) {
	return wp_nonce_url( admin_url( 'admin-post.php?action=wipaco_enquiry_pdf&id=' . $post_id ), 'wipaco_enquiry_pdf_' . $post_id );
}

add_action( 'admin_post_wipaco_enquiry_pdf', function () {
	$id = absint( $_GET['id'] ?? 0 );
	check_admin_referer( 'wipaco_enquiry_pdf_' . $id );
	if ( get_post_type( $id ) !== 'wipaco_enquiry' || ! current_user_can( 'edit_post', $id ) ) {
		wp_die( 'Not allowed.', 403 );
	}
	$pdf = wipaco_enquiry_pdf( $id );
	nocache_headers();
	header( 'Content-Type: application/pdf' );
	header( 'Content-Disposition: inline; filename="' . wipaco_enquiry_pdf_filename( $id ) . '"' );
	header( 'Content-Length: ' . strlen( $pdf ) );
	echo $pdf; // phpcs:ignore WordPress.Security.EscapeOutput -- binary PDF
	exit;
} );

/** Customer phone as WhatsApp digits: 0772 123456 -> 256772123456. */
function wipaco_customer_whatsapp( $phone ) {
	$digits = preg_replace( '/\D/', '', $phone );
	if ( preg_match( '/^0(7\d{8})$/', $digits, $m ) ) {
		return '256' . $m[1];
	}
	return strlen( $digits ) >= 9 ? $digits : '';
}

add_filter( 'post_row_actions', function ( $actions, $post ) {
	if ( $post->post_type === 'wipaco_enquiry' && wipaco_enquiry_data( $post->ID ) ) {
		$actions['pdf'] = '<a href="' . esc_url( wipaco_enquiry_pdf_url( $post->ID ) ) . '" target="_blank">Download PDF</a>';
	}
	return $actions;
}, 10, 2 );

add_action( 'add_meta_boxes_wipaco_enquiry', function ( $post ) {
	add_meta_box( 'wipaco_enquiry_actions', 'Actions', function ( $post ) {
		$data = wipaco_enquiry_data( $post->ID );
		if ( ! $data ) {
			echo '<p>No details saved for this enquiry.</p>';
			return;
		}
		echo '<p><strong>Ref:</strong> ' . esc_html( wipaco_enquiry_ref( $post->ID ) ) . '</p>';
		echo '<p><a class="button button-primary" href="' . esc_url( wipaco_enquiry_pdf_url( $post->ID ) ) . '" target="_blank">Download PDF</a></p>';
		$wa = wipaco_customer_whatsapp( $data['Phone'] ?? '' );
		if ( $wa ) {
			$text = sprintf( 'Hello %s, thank you for your quote request (Ref %s) for %s. ', $data['Name'] ?? '', wipaco_enquiry_ref( $post->ID ), $data['Product'] ?: 'our products' );
			echo '<p><a class="button" href="' . esc_url( 'https://wa.me/' . $wa . '?text=' . rawurlencode( $text ) ) . '" target="_blank" rel="noopener">Reply on WhatsApp</a></p>';
		}
		if ( ! empty( $data['Email'] ) ) {
			echo '<p><a class="button" href="' . esc_url( 'mailto:' . $data['Email'] . '?subject=' . rawurlencode( 'Your quote request ' . wipaco_enquiry_ref( $post->ID ) ) ) . '">Reply by email</a></p>';
		}
	}, 'wipaco_enquiry', 'side', 'high' );
} );
